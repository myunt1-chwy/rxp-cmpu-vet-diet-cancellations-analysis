def wismo_partition(details, evidence, wismo, days, all_contacts=False, all_order_history=False):
    keys = ['followup_days', 'original_customer_id', 'original_order_id', 'original_line_id',
            'reorder_order_id', 'reorder_line_id', 'order_cancel_time', 'reorder_placed_at_utc',
            'prescription_comparison', 'reorder_rx_ids']
    expected = details.loc[details.followup_days.eq(days), keys].copy()
    selected = wismo.loc[wismo.followup_days.eq(days)].copy()
    for col in ['order_cancel_time', 'reorder_placed_at_utc']:
        expected[col] = pd.to_datetime(expected[col], utc=True, format='mixed').astype('datetime64[ns, UTC]')
        selected[col] = pd.to_datetime(selected[col], utc=True, format='mixed').astype('datetime64[ns, UTC]')
    if (selected.duplicated(['followup_days', 'original_customer_id']).any()
            or set(selected[keys].itertuples(index=False, name=None)) != set(expected.itertuples(index=False, name=None))):
        raise ValueError('WISMO evidence differs from selected customer cancellation/reorder intervals')
    if (selected.has_wismo_contact.isna().any() or not selected.has_wismo_contact.isin([True, False]).all()
            or selected.has_wismo_contact.ne(selected.wismo_contact_count.gt(0)).any()):
        raise ValueError('invalid WISMO presence classification')
    if all_contacts:
        if evidence is not None:
            evidence_partition(details, evidence, days)
        selected['source'] = selected.has_wismo_contact.map({
            True: 'Contact: ' + ('Handled contact on aged order' if all_order_history else 'Handled contact before reorder'),
            False: 'Contact: ' + ('No handled contact on aged order' if all_order_history else 'No dated matching contact')})
        selected['target'] = selected.prescription_comparison
        return selected.groupby(['source', 'target']).size().rename('customers').reset_index()
    selected['source'] = selected.prescription_comparison
    different = selected.prescription_comparison.eq('Different prescription')
    if evidence is not None:
        evidence_partition(details, evidence, days)  # Verify exact identity/channel keys first.
        flags = evidence.loc[evidence.followup_days.eq(days)].set_index('original_customer_id')
        states = {(True, True): 'Both upload and decision time', (True, False): 'Upload only',
                  (False, True): 'Decision time only', (False, False): 'Neither'}
        for index, row in selected.loc[different].iterrows():
            item = flags.loc[row.original_customer_id]
            state = states[(bool(item.has_dated_entity_upload), bool(item.has_decision_timestamp))]
            selected.loc[index, 'source'] = f'Evidence: {item.reorder_approval_channel} / {state}'
    else:
        selected.loc[different, 'source'] = 'Channel: ' + selected.loc[different, 'reorder_approval_channel']
    selected['target'] = selected.has_wismo_contact.map({
        True: ('Contact: ' if all_contacts else 'WISMO: ') + ('Handled contact on aged order' if all_order_history else 'Handled contact before reorder'),
        False: ('Contact: ' if all_contacts else 'WISMO: ') + ('No handled contact on aged order' if all_order_history else 'No dated matching contact')})
    return selected.groupby(['source', 'target']).size().rename('customers').reset_index()


def distributions(details, days, evidence=None, wismo=None, all_contacts=False, all_order_history=False):
    all_contacts = all_contacts or all_order_history
    contacts_first = wismo is not None and all_contacts
    subset = details.loc[details.followup_days.eq(days)]
    count = len(subset)
    identity = subset.prescription_comparison.value_counts().rename_axis('category').reset_index(name='customers')
    identity['percent_of_reordered_customers'] = 100 * identity.customers / count if count else 0.
    different = subset.loc[subset.prescription_comparison.eq('Different prescription')]
    channel = different.reorder_approval_channel.value_counts().rename_axis('approval_channel').reset_index(name='customers')
    channel['percent_of_different_prescription_customers'] = 100 * channel.customers / len(different) if len(different) else 0.
    channel['percent_of_reordered_customers'] = 100 * channel.customers / count if count else 0.
    flows = []
    if contacts_first:
        contacts = wismo_partition(details, evidence, wismo, days, all_contacts, all_order_history)
        if contacts.customers.sum() != count:
            raise ValueError('contact partition does not reconcile to reordered customers')
        for node, customers in contacts.groupby('source').customers.sum().items():
            flows.append(dict(transition=1, source='Reordered customers', target=node, prescriptions=int(customers)))
        for row in contacts.itertuples():
            flows.append(dict(transition=2, source=row.source, target=row.target, prescriptions=row.customers))
    else:
        for row in identity.itertuples():
            flows.append(dict(transition=1, source='Reordered customers', target=row.category, prescriptions=row.customers))
    for row in channel.itertuples():
        flows.append(dict(transition=2+int(contacts_first), source='Different prescription', target='Channel: ' + row.approval_channel, prescriptions=row.customers))
    partition = None
    if evidence is not None:
        partition = evidence_partition(details, evidence, days)
        if partition.customers.sum() != len(different):
            raise ValueError('upload/decision partition does not reconcile')
        for row in partition.itertuples():
            flows.append(dict(transition=3+int(contacts_first), source='Channel: ' + row.approval_channel,
                target=f'Evidence: {row.approval_channel} / {row.evidence_category}', prescriptions=row.customers))
    if wismo is not None and not contacts_first:
        contacts = wismo_partition(details, evidence, wismo, days, all_contacts, all_order_history)
        if contacts.customers.sum() != count:
            raise ValueError('WISMO partition does not reconcile to reordered customers')
        for row in contacts.itertuples():
            flows.append(dict(transition=4 if evidence is not None else 3, source=row.source,
                              target=row.target, prescriptions=row.customers))
    flows = pd.DataFrame(flows, columns=['transition', 'source', 'target', 'prescriptions'])
    if identity.customers.sum() != count or channel.customers.sum() != len(different):
        raise ValueError('customer distribution does not reconcile')
    incoming = flows.groupby('target').prescriptions.sum()
    outgoing = flows.groupby('source').prescriptions.sum()
    for node in set(incoming.index) & set(outgoing.index):
        if incoming[node] != outgoing[node]:
            raise ValueError('Sankey flow conservation failed')
    flows['percent_of_reordered_customers'] = 100 * flows.prescriptions / count if count else 0.
    flows.attrs.update(node_alignment='left', bottom_padding=24, node_colors={
        'Reordered customers': '#4E79A7', 'Same prescription': '#8CC9EE',
        'Different prescription': '#F28E2C', 'Unknown': '#BAB0AB', 'Multiple prescriptions': '#AF7AA1'})
    if partition is not None:
        colors = {'Both upload and decision time': '#4E79A7', 'Upload only': '#F28E2C',
                  'Decision time only': '#8CC9EE', 'Neither': '#BAB0AB'}
        flows.attrs['node_colors'].update({f'Evidence: {r.approval_channel} / {r.evidence_category}': colors[r.evidence_category]
                                          for r in partition.itertuples()})
        flows.attrs['columns'] = [('Population: ', 'Reordered customers'), ('Identity: ', 'Prescription identity'),
                                  ('Channel: ', 'Approval channel'), ('Evidence: ', 'Entity upload / decision time')]
    if wismo is not None:
        label = 'Contact: ' if all_contacts else 'WISMO: '
        yes = 'Handled contact on aged order' if all_order_history else 'Handled contact before reorder'
        no = 'No handled contact on aged order' if all_order_history else 'No dated matching contact'
        flows.attrs['node_colors'].update({label + yes: '#AF7AA1', label + no: '#BAB0AB'})
        columns = flows.attrs.get('columns', [('Population: ', 'Reordered customers'),
            ('Identity: ', 'Prescription identity'), ('Channel: ', 'Approval channel')])
        heading = 'Contacts on aged order / all history' if all_order_history else ('Contacts' if all_contacts else 'WISMO') + ' after cancel / before reorder'
        flows.attrs['columns'] = ([columns[0], (label, heading)] + columns[1:] if contacts_first
                                  else columns + [(label, heading)])
    return identity, channel, flows


