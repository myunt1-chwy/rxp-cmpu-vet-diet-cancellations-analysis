HORIZONS = [7, 14, 21]
SELECTION = 'minimum elapsed nanoseconds; earlier reorder timestamp, reorder order/line, original order/line IDs'


def select_customers(outputs):
    return pd.concat([daily.daily_counts(outputs['reorder-matches'], outputs['customers'], days)[0]
                      for days in HORIZONS], ignore_index=True)


def render_sql(selected):
    keys = prescriptions.requested_keys(selected)
    values = json.dumps([[int(r.order_id), int(r.order_line_id)] for r in keys.itertuples()], separators=(',', ':'))
    return Environment(undefined=StrictUndefined).from_string(TEMPLATE.read_text()).render(order_line_keys_json=values)


def load_source(selected, period, baseline_sha, cached):
    sql = render_sql(selected)
    directory = ROOT / 'data' / NAME / period
    parquet, manifest = directory / 'source.parquet', directory / 'source.json'
    expected = dict(sql=sql, sql_sha256=hashlib.sha256(sql.encode()).hexdigest(),
                    baseline_sha256=baseline_sha, customer_selection=SELECTION, followup_days=HORIZONS)
    if cached:
        metadata = json.loads(manifest.read_text())
        if any(metadata.get(k) != v for k, v in expected.items()) or metadata.get('parquet_sha256') != digest(parquet):
            raise ValueError('cached SQL, frozen cohort, selection or fingerprint differs; refresh enrichment')
        frame = pd.read_parquet(parquet)
    else:
        directory.mkdir(parents=True, exist_ok=True)
        generated = ROOT / 'src/autogenerated' / NAME / period
        generated.mkdir(parents=True, exist_ok=True)
        query = generated / 'aged_order_reorder_prescription_sankeys.sql'
        write_text(query, sql + '\n')
        manifest.unlink(missing_ok=True)
        subprocess.run([sys.executable, str(RUNNER), str(query), '--output-parquet', str(parquet.relative_to(ROOT)),
                        '--sql-log-dir', str((generated / 'sql-history').relative_to(ROOT))], cwd=ROOT, check=True)
        frame = pd.read_parquet(parquet).rename(columns=str.lower)
        metadata = dict(expected, parquet_sha256=digest(parquet),
                        extracted_at_utc=datetime.now(timezone.utc).isoformat(),
                        warehouse=frame.extraction_warehouse.unique().tolist())
    return frame, metadata, manifest


def summarize(selected, associations, raw):
    source = raw.rename(columns=str.lower).copy()
    registry = source.loc[source.rx_id.notna(), ['rx_id', 'matched_rx_id', 'approval_channel', 'prescription_rows']].drop_duplicates()
    if (registry.rx_id.duplicated().any() or not registry.prescription_rows.isin([0, 1]).all()
            or registry.prescription_rows.eq(1).ne(registry.matched_rx_id.notna()).any()
            or (registry.prescription_rows.eq(0) & registry.approval_channel.notna()).any()
            or (registry.matched_rx_id.notna() & registry.rx_id.ne(registry.matched_rx_id)).any()):
        raise ValueError('duplicate or inconsistent prescription registry records')
    nulls = source.loc[source.rx_id.isna()]
    if nulls.matched_rx_id.notna().any() or nulls.approval_channel.notna().any() or nulls.prescription_rows.ne(0).any():
        raise ValueError('registry evidence without prescription ID')
    details, audits = [], []
    evidence = source[['order_id', 'order_line_id', 'rx_id', 'rx_usage_id', 'shipment_rows']]
    expected_keys = prescriptions.requested_keys(selected)
    actual_keys = evidence[['order_id', 'order_line_id']].drop_duplicates().sort_values(['order_id', 'order_line_id']).reset_index(drop=True)
    if not actual_keys.equals(expected_keys.reset_index(drop=True).astype(actual_keys.dtypes.to_dict())):
        raise ValueError('prescription extract keys do not match selected customer pairs')
    for days in HORIZONS:
        pairs = selected.loc[selected.followup_days.eq(days)]
        if pairs.original_customer_id.duplicated().any():
            raise ValueError('customer counted more than once within horizon')
        keys = prescriptions.requested_keys(pairs)
        scoped = evidence.merge(keys, on=['order_id', 'order_line_id'], validate='many_to_one')
        if pairs.empty:
            continue
        comparison, _, _, audit = prescriptions.summarize(pairs, associations, scoped)
        different = comparison.prescription_comparison.eq('Different prescription')
        comparison['reorder_approval_channel'] = pd.NA
        # A Different classification guarantees one complete RX_ID on each side.
        different_ids = comparison.loc[different, 'reorder_rx_ids']
        if len(different_ids):
            lookup = registry.loc[registry.rx_id.isin(different_ids)].copy()
            lines = comparison.loc[different, ['original_customer_id', 'reorder_order_id', 'reorder_line_id', 'shipped_by_as_of', 'reorder_rx_ids']].rename(columns={'reorder_rx_ids': 'rx_id'})
            enriched, _, _, _ = channels.summarize(lines.drop_duplicates(), lookup)
            mapping = enriched.set_index('original_customer_id').channel
            comparison.loc[different, 'reorder_approval_channel'] = comparison.loc[different, 'original_customer_id'].map(mapping)
            if comparison.loc[different, 'reorder_approval_channel'].isna().any():
                raise ValueError('missing different-prescription channel classification')
        details.append(comparison)
        audits.append(audit.assign(followup_days=days))
    if not details:
        # Keep the full export schema for empty reordered populations.
        empty = selected.copy()
        for name in ['prescription_comparison', 'reorder_approval_channel']:
            empty[name] = pd.Series(dtype='string')
        return empty, pd.DataFrame(columns=['measure', 'count', 'followup_days'])
    return pd.concat(details, ignore_index=True), pd.concat(audits, ignore_index=True)


def load_evidence(details, metadata, period):
    # Import locally: the evidence workflow also reuses the frozen selection above.
    from src.python import create_aged_order_reorder_upload_approval_evidence as evidence
    pairs, requests, lines = evidence.requests_for(details)
    dependencies = dict(baseline=metadata['baseline_sha256'],
                        prescription_channels=metadata['parquet_sha256'], customer_selection=SELECTION)
    raw, source_meta, _ = evidence.load_source(requests, lines, period, dependencies,
                                              metadata['as_of_date'], True)
    outputs = evidence.summarize(pairs, requests, lines, raw, metadata['as_of_date'])
    return outputs['selected-customers'], source_meta


def evidence_partition(details, evidence, days):
    keys = ['followup_days', 'original_customer_id', 'original_order_id', 'original_line_id',
            'reorder_order_id', 'reorder_line_id', 'reorder_rx_ids', 'reorder_approval_channel']
    expected = details.loc[details.followup_days.eq(days) & details.prescription_comparison.eq('Different prescription'), keys]
    selected = evidence.loc[evidence.followup_days.eq(days)].copy()
    if (selected.duplicated(['followup_days', 'original_customer_id']).any()
            or set(selected[keys].itertuples(index=False, name=None)) != set(expected.itertuples(index=False, name=None))):
        raise ValueError('upload/decision evidence differs from selected different-prescription customers')
    flags = ['has_dated_entity_upload', 'has_decision_timestamp']
    if selected[flags].isna().any().any() or not selected[flags].isin([True, False]).all().all():
        raise ValueError('missing or invalid upload/decision presence flags')
    states = {(True, True): 'Both upload and decision time', (True, False): 'Upload only',
              (False, True): 'Decision time only', (False, False): 'Neither'}
    selected['evidence_category'] = [states[(bool(u), bool(d))] for u, d in selected[flags].itertuples(index=False, name=None)]
    return selected.groupby(['reorder_approval_channel', 'evidence_category']).size().rename('customers').reset_index().rename(
        columns={'reorder_approval_channel': 'approval_channel'})


