"""Prepare readable SQL listings for the data-verification tables."""
import hashlib
import json
from pathlib import Path

import sqlparse

from src.python.markdown_tables import write_text

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT/'src/autogenerated/data-verification-sql'
TABLES = {
    'source-entries': ('tab:upload-source-resource-types', [
        ('upload_data_verification', 'Source-entry and prescription-ID counts'),
        ('upload_data_verification_rx_ids_validation', 'Independent prescription-ID count check'),
    ]),
    'source-time-coverage': ('tab:upload-source-time-coverage', [
        ('upload_source_time_coverage', 'Minimum and maximum source creation timestamps in UTC'),
    ]),
    'vet-diet-approval-channels': ('tab:upload-vet-diet-approval-channels', [
        ('upload_vet_diet_approval_channels', 'All upload prescription IDs joined to the prescription registry'),
        ('upload_vet_diet_approval_channels_validation', 'Independent approval-channel and join-coverage aggregation'),
    ]),
    'approved-prescription-coverage': ('tab:cmpu-approved-prescription-upload-coverage', [
        ('cmpu_approved_prescription_upload_coverage', 'Vet-diet customer-upload prescription joins by prescription source and status'),
        ('cmpu_approved_prescription_upload_coverage_validation', 'Independent prescription-ID membership aggregation by source and status'),
    ]),
    'diet-orders': ('tab:diet-upload-source-cancel-reasons', [
        ('diet_upload_source_orders', 'Diet uploads and their associated order IDs'),
        ('diet_upload_linked_orders', 'ECOM order records for linked diet uploads'),
        ('diet_upload_source_orders_validation', 'Independent source-by-reason aggregation'),
    ]),
    'null-resource-orders': ('tab:null-resource-upload-order-cancel-reasons', [
        ('null_resource_upload_context', 'NULL-type uploads and their context identifiers'),
        ('null_resource_upload_orders', 'ECOM order records linked to NULL-type uploads'),
        ('null_resource_upload_validation', 'Independent identifier and reason aggregation'),
    ]),
}


def format_sql(sql, source_name):
    """Format SQL for listings without changing literals, expressions or comments."""
    formatted = sqlparse.format(sql, keyword_case='upper', reindent=False).rstrip() + '\n'

    def tokens(text):
        return [token.normalized for statement in sqlparse.parse(text)
                for token in statement.flatten() if not token.is_whitespace]

    if tokens(sql) != tokens(formatted):
        raise ValueError(f'SQL formatting changed tokens in {source_name}')
    return formatted


def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    hashes = {}
    for name, (label, queries) in TABLES.items():
        lines = [r'\paragraph*{SQL for Table~\ref{' + label + '}}',
                 r'\nolinenumbers']
        if name == 'vet-diet-approval-channels':
            lines.append('The first query links distinct uploaded prescription IDs to the registry. '
                         'The table renderer retains matched vet-diet prescriptions and counts '
                         'their approval channels. The second query independently verifies channel '
                         'counts and the unmatched, non-vet-diet and unknown-category populations.')
        elif name == 'approved-prescription-coverage':
            lines.append('The first query returns one record per qualifying prescription, joined '
                         'to distinct upload-source prescription IDs on prescription ID only. The second '
                         'query independently counts upload-source membership and overlap by prescription '
                         'source and current status, including source subtotals, status subtotals and overall.')
        elif name == 'source-time-coverage':
            lines.append('This query calculates creation-time extrema by resource type and overall. '
                         'Notification-service timestamps are converted to UTC before aggregation; '
                         'missing timestamps do not contribute to the minimum or maximum.')
        elif name != 'source-entries':
            lines.append('The first two queries extract the source records used by the table renderer. '
                         'The final query independently aggregates the counts in Snowflake. '
                         'Orders count once per source; the table renderer also calculates '
                         'percentages and, for the source comparison, the count difference.')
        else:
            lines.append('The primary query returns the displayed counts. The independent check '
                         'expands the ID lists and counts distinct upload IDs; these counts '
                         'reconcile to the physical-row totals in this extract.')
        for filename, title in queries:
            source = ROOT/'src/sql'/f'{filename}.sql'
            sql = source.read_text()
            # Preserve the source's deliberate CTE/function indentation. Automatic
            # reindentation creates very deep alignment in Snowflake lambdas and
            # scalar subqueries; listings wraps long lines for the printed page.
            formatted = format_sql(sql, source.name)
            write_text(DESTINATION/f'{filename}.sql', formatted)
            hashes[source.name] = hashlib.sha256(sql.encode()).hexdigest()
            lines.extend([r'\Needspace{6\baselineskip}',
                          r'\lstinputlisting[style=verification-sql,title={' + title +
                          r'}]{../autogenerated/data-verification-sql/' + filename + '.sql}'])
        lines.append(r'\linenumbers')
        write_text(DESTINATION/f'{name}.tex', '\n'.join(lines) + '\n')
    write_text(DESTINATION/'source-hashes.json', json.dumps(hashes, indent=2) + '\n')
    print(f'Prepared SQL listings for all {len(TABLES)} data-verification tables.')


if __name__ == '__main__':
    main()
