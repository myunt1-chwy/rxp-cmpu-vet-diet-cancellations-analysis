NAME = 'aged-order-reorder-upload-approval-evidence'
TEMPLATE = ROOT / 'src/sql/aged_order_reorder_upload_approval_evidence.sql'
LINE_KEYS = ['rx_id', 'customer_id', 'order_id', 'order_line_id']
LINE_COLUMNS = LINE_KEYS + ['line_source_rows', 'line_rx_variants', 'line_rx_id', 'missing_line_rx_rows',
                           'min_approved_denied_datetime', 'approval_variants', 'populated_approval_rows']


def requests_for(details):
    pairs = details.loc[details.prescription_comparison.eq('Different prescription')].copy()
    pairs['rx_id'] = pairs.reorder_rx_ids
    pairs['customer_id'] = pairs.original_customer_id
    requests = pairs[['rx_id', 'customer_id', 'reorder_approval_channel']].drop_duplicates().rename(
        columns={'reorder_approval_channel': 'channel'})
    if requests.rx_id.duplicated().any() or requests.channel.isna().any():
        raise ValueError('inconsistent customer or channel for frozen prescription')
    requests['approval_channel'] = requests.channel
    lines = pairs[['rx_id', 'customer_id', 'reorder_order_id', 'reorder_line_id']].drop_duplicates().rename(
        columns={'reorder_order_id': 'order_id', 'reorder_line_id': 'order_line_id'})
    if lines.duplicated(['order_id', 'order_line_id']).any():
        raise ValueError('conflicting frozen reorder line prescription or customer')
    return pairs, requests, lines


def render_sql(requests, lines, as_of):
    upload_sql = uploads.render_sql(requests, as_of)
    records = []
    for row in lines.sort_values(LINE_KEYS).itertuples():
        for value in [row.customer_id, row.order_id, row.order_line_id]:
            if pd.isna(value) or value != int(value):
                raise ValueError('invalid frozen line key')
        records.append([row.rx_id, int(row.customer_id), int(row.order_id), int(row.order_line_id)])
    return Environment(undefined=StrictUndefined).from_string(TEMPLATE.read_text()).render(
        upload_sql=upload_sql, requested_lines_json=json.dumps(records, separators=(',', ':')).replace("'", "''"))


def load_source(requests, lines, period, dependencies, as_of, cached):
    sql = render_sql(requests, lines, as_of)
    directory = ROOT / 'data' / NAME / period
    parquet, manifest = directory / 'source.parquet', directory / 'source.json'
    expected = dict(sql=sql, sql_sha256=hashlib.sha256(sql.encode()).hexdigest(), dependencies=dependencies)
    if cached:
        metadata = json.loads(manifest.read_text())
        if any(metadata.get(k) != v for k, v in expected.items()) or metadata.get('parquet_sha256') != digest(parquet):
            raise ValueError('cached SQL, frozen inputs or fingerprint differs; refresh evidence')
        raw = pd.read_parquet(parquet)
    else:
        directory.mkdir(parents=True, exist_ok=True)
        generated = ROOT / 'src/autogenerated' / NAME / period
        generated.mkdir(parents=True, exist_ok=True)
        query = generated / 'aged_order_reorder_upload_approval_evidence.sql'
        write_text(query, sql + '\n')
        manifest.unlink(missing_ok=True)
        subprocess.run([sys.executable, str(RUNNER), str(query), '--output-parquet', str(parquet.relative_to(ROOT)),
                        '--sql-log-dir', str((generated / 'sql-history').relative_to(ROOT))], cwd=ROOT, check=True)
        raw = pd.read_parquet(parquet).rename(columns=str.lower)
        metadata = dict(expected, parquet_sha256=digest(parquet), extracted_at_utc=datetime.now(timezone.utc).isoformat(),
                        warehouse=raw.extraction_warehouse.unique().tolist())
    return raw, metadata, manifest


def summarize(pairs, requests, lines, raw, as_of):
    source = raw.rename(columns=str.lower).copy()
    source['min_approved_denied_datetime'] = pd.to_datetime(source.min_approved_denied_datetime, utc=True, format='mixed').astype('datetime64[ns, UTC]')
    evidence = source[LINE_COLUMNS].drop_duplicates()
    expected = set(lines.itertuples(index=False, name=None))
    actual = set(evidence[LINE_KEYS].itertuples(index=False, name=None))
    if actual != expected or evidence.duplicated(LINE_KEYS).any():
        raise ValueError('missing, extra or conflicting selected-line evidence')
    if source.duplicated(LINE_KEYS + ['upload_id']).any():
        raise ValueError('duplicate selected-line/upload association')
    for col in ['line_source_rows', 'line_rx_variants', 'missing_line_rx_rows', 'approval_variants', 'populated_approval_rows']:
        if evidence[col].isna().any() or evidence[col].lt(0).any() or evidence[col].mod(1).ne(0).any():
            raise ValueError('invalid line evidence count')
    populated = evidence.min_approved_denied_datetime.notna()
    if (populated.ne(evidence.populated_approval_rows.gt(0)).any()
            or evidence.approval_variants.gt(evidence.populated_approval_rows).any()
            or evidence.populated_approval_rows.gt(evidence.line_source_rows).any()
            or populated.ne(evidence.approval_variants.gt(0)).any()):
        raise ValueError('inconsistent populated decision timestamp evidence')
    if (not evidence.line_source_rows.gt(0).all() or not evidence.line_rx_variants.eq(1).all()
            or not evidence.missing_line_rx_rows.eq(0).all() or evidence.line_rx_id.ne(evidence.rx_id).any()):
        raise ValueError('current line prescription differs from frozen different-prescription selection')
    # A prescription may appear on multiple selected lines/horizons. Validate identical
    # upload evidence across those lines before collapsing to one RX_ID/customer lookup.
    upload_columns = [c for c in source if c not in set(LINE_COLUMNS) - {'rx_id', 'customer_id'}]
    upload_source = source[upload_columns].drop_duplicates()
    rx, _, associations, _, upload_audit = uploads.summarize(pairs.drop(columns=['rx_id', 'customer_id']), requests, upload_source, as_of)
    selected = pairs.merge(evidence, left_on=['rx_id', 'customer_id', 'reorder_order_id', 'reorder_line_id'],
        right_on=LINE_KEYS, how='left', validate='many_to_one')
    selected = selected.merge(rx.drop(columns=['approval_channel', 'channel']), on=['rx_id', 'customer_id'],
                              how='left', validate='many_to_one')
    selected['has_dated_entity_upload'] = selected.dated_uploads.gt(0)
    selected['has_any_entity_upload'] = selected.matching_uploads.gt(0)
    selected['has_decision_timestamp'] = selected.min_approved_denied_datetime.notna()
    rows = []
    for key, group in selected.groupby(['followup_days', 'rx_id', 'customer_id'], sort=True):
        first = group.iloc[0]
        rows.append(dict(followup_days=key[0], rx_id=key[1], customer_id=key[2],
            approval_channel=first.reorder_approval_channel, selected_customers=group.original_customer_id.nunique(),
            selected_reorder_lines=len(group[['reorder_order_id', 'reorder_line_id']].drop_duplicates()),
            has_dated_entity_upload=bool(group.has_dated_entity_upload.any()),
            has_any_entity_upload=bool(group.has_any_entity_upload.any()),
            has_recorded_file_upload=bool(group.has_recorded_file_upload.any()),
            undated_uploads=int(first.undated_uploads), dated_uploads=int(first.dated_uploads),
            first_upload_at_utc=first.first_upload_at_utc,
            has_decision_timestamp=bool(group.has_decision_timestamp.any()),
            min_approved_denied_datetime=group.min_approved_denied_datetime.min(),
            decision_after_cutoff=bool(group.min_approved_denied_datetime.gt(pd.Timestamp(as_of, tz='UTC')).any())))
    prescriptions = pd.DataFrame(rows)
    summaries = []
    for days in sankeys.HORIZONS:
        subset = prescriptions.loc[prescriptions.followup_days.eq(days)]
        for channel, group in [('All channels', subset), *list(subset.groupby('approval_channel'))]:
            upload, decision = group.has_dated_entity_upload, group.has_decision_timestamp
            measures = {
                'Both upload and decision timestamp': upload & decision,
                'Upload only': upload & ~decision,
                'Decision timestamp only': ~upload & decision,
                'Neither': ~upload & ~decision,
                'Any dated entity upload': upload,
                'Any non-null decision timestamp': decision,
                'Upload or decision timestamp (union)': upload | decision,
                'Any entity including undated': group.has_any_entity_upload,
                'Undated entity only': group.has_any_entity_upload & ~upload,
                'Dated entity with HAS_UPLOADED_FILE=true': group.has_recorded_file_upload,
                'Decision timestamp after cutoff': group.decision_after_cutoff,
            }
            if sum(int(measures[k].sum()) for k in list(measures)[:4]) != len(group):
                raise ValueError('overlap categories do not reconcile')
            for measure, flags in measures.items():
                count = int(flags.sum())
                summaries.append(dict(followup_days=days, approval_channel=channel, measure=measure, count=count,
                    denominator=len(group), percent=100 * count / len(group) if len(group) else None))
    audit = pd.concat([upload_audit.assign(scope='All horizons, distinct RX_IDs'), pd.DataFrame([
        dict(measure='Selected different-prescription customer/horizon rows', count=len(pairs), scope='All horizons'),
        dict(measure='Distinct selected reorder lines', count=len(evidence), scope='All horizons'),
        dict(measure='Lines with multiple populated approval minima', count=int(evidence.approval_variants.gt(1).sum()), scope='All horizons'),
        dict(measure='Lines with partial missing decision evidence', count=int((evidence.populated_approval_rows.gt(0) & evidence.populated_approval_rows.lt(evidence.line_source_rows)).sum()), scope='All horizons')
    ])], ignore_index=True)
    return {'summary': pd.DataFrame(summaries), 'prescriptions': prescriptions, 'selected-customers': selected,
            'upload-associations': associations, 'line-evidence': evidence, 'audit': audit}


@click.command()
@click.option('--start-date', default='2026-08-15', show_default=True)
@click.option('--end-date', default='2026-10-15', show_default=True)
@click.option('--as-of-date', default='2026-10-27', show_default=True)
@click.option('--cached', is_flag=True)
@click.option('--print-sql', is_flag=True)
def main(start_date, end_date, as_of_date, cached, print_sql):
    try:
        base, bmeta, period = sankeys.windows.load_source(start_date, end_date, as_of_date, True, require_same_pet=True, include_21_days=True)
        windows = sankeys.windows.summarize(base, start_date, end_date, as_of_date, require_same_pet=True, include_21_days=True)
        chosen = sankeys.select_customers(windows)
        rx_source, rmeta, _ = sankeys.load_source(chosen, period, bmeta['parquet_sha256'], True)
        details, _ = sankeys.summarize(chosen, windows['associations'], rx_source)
        pairs, requests, lines = requests_for(details)
        if print_sql:
            click.echo(render_sql(requests, lines, as_of_date)); return
        dependencies = dict(baseline=bmeta['parquet_sha256'], prescription_channels=rmeta['parquet_sha256'], customer_selection=sankeys.SELECTION)
        raw, metadata, manifest = load_source(requests, lines, period, dependencies, as_of_date, cached)
        outputs = summarize(pairs, requests, lines, raw, as_of_date)
        metadata.update(start_date=start_date, end_date_exclusive=end_date, as_of_date=as_of_date)
        tables, prefix = table_layout(ROOT, NAME, period)
        tables.mkdir(parents=True, exist_ok=True)
        note = (f'Frozen REFNUM 24 shortest-delay selected same-customer/product/pet reorders at 7/14/21 days; '
            f'original CMPU vet-diet CUSTOMER_UPLOAD prescriptions [{start_date}, {end_date}) UTC. '
            'Only Different prescription selections are included. Counts deduplicate RX_ID/customer within each horizon; '
            'one prescription can appear in several horizons, which must not be summed. Different does not imply newly created. '
            f'DIET_PRESCRIPTION entity uploads match expanded RX_ID and numeric CUSTOMER_ID across all history through {as_of_date} 00:00 UTC inclusive. '
            'Primary upload presence requires a dated entity by cutoff; undated entities and HAS_UPLOADED_FILE flags are reported separately. '
            'No file-flag, order, deletion or after-cancellation upload filter. Entity presence alone does not prove a file was uploaded. '
            'Decision evidence means non-null MIN_APPROVED_DENIED_DATETIME on a selected reordered line, taking the earliest populated minimum across shipment rows '
            'and selected lines for that prescription/horizon. RX_USAGE_ID does not define prescription identity. '
            'The field is interpreted as UTC, as in REFNUM 20. Decision timestamps are not cutoff-filtered: this is a current non-null check, with after-cutoff values audited. '
            'Current entity links, file flags and line prescription associations are lookup-time state. Approval channels remain frozen from REFNUM 24. '
            'Four exclusive overlap categories are Both, Upload only, Decision timestamp only and Neither. Other summary measures overlap.\n\n'
            f"Source SHA-256 {metadata['parquet_sha256']}; extracted {metadata['extracted_at_utc']}.\n\n")
        hashes = {}
        for kind, frame in outputs.items():
            table = tables / f'{prefix}{kind}.md'
            write_text(table, f'# Different reorder prescriptions: upload and decision evidence ({kind})\n\n' + note + markdown_table(frame) + '\n')
            path = manifest.parent / f'{kind}.parquet'
            frame.to_parquet(path, index=False)
            hashes[str(path.relative_to(ROOT))] = digest(path)
            hashes[str(table.relative_to(ROOT))] = digest(table)
        write_text(manifest.parent / 'exports.json', json.dumps(dict(dependencies=dependencies, source_sha256=metadata['parquet_sha256'], files=hashes), indent=2) + '\n')
        write_text(manifest, json.dumps(metadata, indent=2) + '\n')
        click.echo(outputs['summary'].loc[outputs['summary'].approval_channel.eq('All channels')].to_string(index=False))
        click.echo(outputs['audit'].to_string(index=False))
        click.echo(f'Tables: {tables}')
    except (ValueError, OSError, KeyError, subprocess.CalledProcessError) as error:
        raise click.ClickException(str(error)) from error


if __name__ == '__main__':
    main()
