NAME = 'aged-order-reorder-wismo'
TEMPLATE = ROOT / 'src/sql/aged_order_reorder_wismo.sql'
ALL_TEMPLATE = ROOT / 'src/sql/aged_order_reorder_all_contacts.sql'
ALL_HISTORY_TEMPLATE = ROOT / 'src/sql/aged_order_reorder_all_order_contacts.sql'
INTERVAL = ['original_order_id', 'order_cancel_time', 'reorder_placed_at_utc']
TIMEZONES = ['UTC', 'America/New_York']


def timestamp_text(value):
    return pd.Timestamp(value).tz_convert('UTC').tz_localize(None).isoformat(sep=' ', timespec='nanoseconds')


def requests_for(details):
    selected = details.copy()
    if selected.duplicated(['followup_days', 'original_customer_id']).any():
        raise ValueError('multiple selected reorders per customer/horizon')
    for col in INTERVAL[1:]:
        selected[col] = pd.to_datetime(selected[col], utc=True, format='mixed').astype('datetime64[ns, UTC]')
    if selected[INTERVAL].isna().any().any() or selected.order_cancel_time.ge(selected.reorder_placed_at_utc).any():
        raise ValueError('invalid selected cancellation/reorder interval')
    if selected.original_order_id.mod(1).ne(0).any():
        raise ValueError('invalid original order ID')
    intervals = selected[INTERVAL].drop_duplicates().sort_values(INTERVAL).reset_index(drop=True)
    intervals.insert(0, 'request_id', range(1, len(intervals) + 1))
    return selected.merge(intervals, on=INTERVAL, how='left', validate='many_to_one'), intervals


def render_sql(intervals, contact_timezone, all_contacts=False, all_order_history=False):
    if contact_timezone not in TIMEZONES:
        raise ValueError('contact timezone must be explicitly UTC or America/New_York')
    if intervals.empty:
        raise ValueError('no selected reorder intervals to check')
    records = [[int(r.request_id), int(r.original_order_id), timestamp_text(r.order_cancel_time),
                timestamp_text(r.reorder_placed_at_utc)] for r in intervals.itertuples()]
    expression = ('c.SESSION_START_DTTM' if contact_timezone == 'UTC' else
                  "CONVERT_TIMEZONE('America/New_York', 'UTC', c.SESSION_START_DTTM)")
    template = ALL_HISTORY_TEMPLATE if all_order_history else ALL_TEMPLATE if all_contacts else TEMPLATE
    return Environment(undefined=StrictUndefined).from_string(template.read_text()).render(
        requested_json=json.dumps(records, separators=(',', ':')), contact_time_expression=expression)


def load_source(intervals, period, dependencies, contact_timezone, cached, all_contacts=False, all_order_history=False):
    all_contacts = all_contacts or all_order_history
    sql = render_sql(intervals, contact_timezone, all_contacts, all_order_history)
    if all_contacts:
        period += '_all-handled-contacts'
    if all_order_history:
        period += '_all-order-history'
    directory = ROOT / 'data' / NAME / period / contact_timezone.replace('/', '-')
    parquet, manifest = directory / 'source.parquet', directory / 'source.json'
    expected = dict(sql=sql, sql_sha256=hashlib.sha256(sql.encode()).hexdigest(), dependencies=dependencies,
                    contact_timezone=contact_timezone)
    if all_contacts:
        expected['contact_scope'] = 'all-handled'
    if all_order_history:
        expected['contact_time_scope'] = 'all-order-history'
    if cached:
        metadata = json.loads(manifest.read_text())
        if any(metadata.get(k) != v for k, v in expected.items()) or metadata.get('parquet_sha256') != digest(parquet):
            raise ValueError('cached SQL, selected intervals, timezone or fingerprint differs; refresh WISMO')
        raw = pd.read_parquet(parquet)
    else:
        directory.mkdir(parents=True, exist_ok=True)
        generated = ROOT / 'src/autogenerated' / NAME / period / contact_timezone.replace('/', '-')
        generated.mkdir(parents=True, exist_ok=True)
        query = generated / 'aged_order_reorder_wismo.sql'
        write_text(query, sql + '\n')
        manifest.unlink(missing_ok=True)
        subprocess.run([sys.executable, str(RUNNER), str(query), '--output-parquet', str(parquet.relative_to(ROOT)),
                        '--sql-log-dir', str((generated / 'sql-history').relative_to(ROOT))], cwd=ROOT, check=True)
        raw = pd.read_parquet(parquet).rename(columns=str.lower)
        metadata = dict(expected, parquet_sha256=digest(parquet), extracted_at_utc=datetime.now(timezone.utc).isoformat(),
                        warehouse=raw.extraction_warehouse.unique().tolist())
    return raw, metadata, manifest


def summarize(selected, intervals, raw, contact_timezone, all_contacts=False, all_order_history=False):
    all_contacts = all_contacts or all_order_history
    if contact_timezone not in TIMEZONES:
        raise ValueError('unknown contact timezone')
    source = raw.rename(columns=str.lower).copy()
    for col in INTERVAL[1:] + ['first_wismo_dttm', 'last_wismo_dttm']:
        source[col] = pd.to_datetime(source[col], utc=True, format='mixed').astype('datetime64[ns, UTC]')
    if source.request_id.isna().any() or source.request_id.mod(1).ne(0).any():
        raise ValueError('invalid WISMO interval key')
    # Snowflake NUMBER(38,0) arrives through Parquet as Decimal, while our
    # deterministic request index is int64; pandas indexes do not equate them.
    source['request_id'] = source.request_id.astype('int64')
    if source.request_id.duplicated().any() or set(source.request_id) != set(intervals.request_id):
        raise ValueError('missing, extra or duplicate WISMO interval keys')
    expected = intervals.set_index('request_id')
    for row in source.itertuples():
        reference = expected.loc[row.request_id]
        if any(getattr(row, col) != reference[col] for col in INTERVAL):
            raise ValueError('WISMO order or interval differs from frozen selection')
    counts = ['wismo_contact_count', 'distinct_wismo_sessions', 'all_handled_wismo_order_rows', 'missing_session_time_rows']
    if source[counts].isna().any().any() or source[counts].lt(0).any().any() or source[counts].mod(1).ne(0).any().any():
        raise ValueError('invalid WISMO evidence counts')
    if (source.wismo_contact_count.gt(source.all_handled_wismo_order_rows).any()
            or source.missing_session_time_rows.gt(source.all_handled_wismo_order_rows).any()):
        raise ValueError('inconsistent WISMO order audit counts')
    if all_order_history and source.wismo_contact_count.ne(source.all_handled_wismo_order_rows).any():
        raise ValueError('all-history contact count must include every handled order contact')
    contacts = []
    duplicate_legs = missing_sessions = missing_channels = 0
    for row in source.itertuples():
        records = json.loads(row.matched_contacts_json)
        if not isinstance(records, list) or len(records) != row.wismo_contact_count:
            raise ValueError('WISMO count differs from matching contact rows')
        times, sessions, channels, legs = [], set(), set(), []
        for record in records:
            if (record['order_id'] != row.original_order_id or (not all_contacts and record['category_wismo_flag'] is not True)
                    or record['handled_flag'] is not True):
                raise ValueError('WISMO contact order or flags disagree')
            stamp = pd.Timestamp(record['contact_at_utc'], tz='UTC') if record['contact_at_utc'] is not None else pd.NaT
            raw_stamp = pd.Timestamp(record['session_start_dttm_raw']) if record['session_start_dttm_raw'] is not None else pd.NaT
            if pd.isna(stamp) or pd.isna(raw_stamp):
                if not all_order_history or pd.isna(stamp) != pd.isna(raw_stamp):
                    raise ValueError('missing or inconsistent contact timestamp')
            else:
                converted = raw_stamp.tz_localize(contact_timezone).tz_convert('UTC')
                if stamp != converted or (not all_order_history and not row.order_cancel_time < stamp < row.reorder_placed_at_utc):
                    raise ValueError('WISMO contact outside strict cancellation/reorder interval or incorrect timezone')
                times.append(stamp)
            if record['session_id'] is not None: sessions.add(record['session_id'])
            else: missing_sessions += 1
            if record['session_channel'] is not None: channels.add(record['session_channel'])
            else: missing_channels += 1
            if record['leg_id'] is not None: legs.append(record['leg_id'])
            contacts.append(dict(request_id=row.request_id, **record))
        duplicate_legs += len(legs) - len(set(legs))
        if (len(sessions) != row.distinct_wismo_sessions or ', '.join(sorted(channels)) != row.wismo_channels
                or (times and (min(times) != row.first_wismo_dttm or max(times) != row.last_wismo_dttm))
                or (not times and (pd.notna(row.first_wismo_dttm) or pd.notna(row.last_wismo_dttm)))):
            raise ValueError('WISMO session/channel/min/max aggregates disagree with contact evidence')
    columns = ['request_id', 'wismo_contact_count', 'distinct_wismo_sessions', 'first_wismo_dttm', 'last_wismo_dttm',
               'wismo_channels', 'all_handled_wismo_order_rows', 'missing_session_time_rows']
    details = selected.merge(source[columns], on='request_id', how='left', validate='many_to_one')
    details['has_wismo_contact'] = details.wismo_contact_count.gt(0)
    rows = []
    for days in sankeys.HORIZONS:
        subset = details.loc[details.followup_days.eq(days)]
        for comparison, group in [('All reordered customers', subset), *list(subset.groupby('prescription_comparison'))]:
            count = int(group.has_wismo_contact.sum())
            rows.append(dict(followup_days=days, prescription_comparison=comparison, reordered_customers=len(group),
                customers_with_wismo=count, customers_without_dated_wismo=len(group)-count,
                percent_with_wismo=100*count/len(group) if len(group) else None,
                matching_contact_legs=int(group.wismo_contact_count.sum()),
                matching_session_interval_associations=int(group.distinct_wismo_sessions.sum()),
                customers_with_undated_order_contacts=int(group.missing_session_time_rows.gt(0).sum())))
    audit = pd.DataFrame([
        ('Selected customer/horizon rows', len(selected)), ('Distinct order/time intervals', len(intervals)),
        ('Matching contact-leg/interval associations', len(contacts)),
        ('Repeated non-null LEG_ID within matching intervals (retained in COUNT(*))', duplicate_legs),
        ('Matching leg/interval rows missing SESSION_ID', missing_sessions),
        ('Matching leg/interval rows missing SESSION_CHANNEL', missing_channels),
        ('Intervals with undated handled WISMO order contacts', int(source.missing_session_time_rows.gt(0).sum()))
    ], columns=['measure', 'count'])
    events = pd.DataFrame(contacts, columns=['request_id', 'order_id', 'leg_id', 'session_id', 'session_channel',
        'session_start_dttm_raw', 'contact_at_utc', 'category_wismo_flag', 'handled_flag'])
    return {'summary': pd.DataFrame(rows), 'selected-customers': details, 'intervals': source,
            'contact-interval-associations': events, 'audit': audit}


def contact_columns(frame, all_order_history=False):
    """Use neutral metric names for the all-category export; retain raw source flag names."""
    return frame.rename(columns={
        'wismo_contact_count': 'contact_count', 'distinct_wismo_sessions': 'distinct_contact_sessions',
        'first_wismo_dttm': 'first_contact_dttm', 'last_wismo_dttm': 'last_contact_dttm',
        'wismo_channels': 'contact_channels', 'all_handled_wismo_order_rows': 'all_handled_contact_order_rows',
        'has_wismo_contact': 'has_handled_contact', 'customers_with_wismo': 'customers_with_contact',
        'customers_without_dated_wismo': 'customers_without_contact' if all_order_history else 'customers_without_dated_contact',
        'percent_with_wismo': 'percent_with_contact'})


@click.command()
@click.option('--start-date', default='2026-08-15', show_default=True)
@click.option('--end-date', default='2026-10-15', show_default=True)
@click.option('--as-of-date', default='2026-10-27', show_default=True)
@click.option('--contact-timezone', type=click.Choice(TIMEZONES), required=True)
@click.option('--cached', is_flag=True)
@click.option('--print-sql', is_flag=True)
@click.option('--all-contacts', is_flag=True, help='Keep HANDLED_FLAG=TRUE and remove the CATEGORY_WISMO_FLAG filter.')
@click.option('--all-order-history', is_flag=True, help='All handled categories on the aged order, without any contact time filter; includes undated contacts.')
def main(start_date, end_date, as_of_date, contact_timezone, cached, print_sql, all_contacts, all_order_history):
    try:
        all_contacts = all_contacts or all_order_history
        base, bmeta, period = sankeys.windows.load_source(start_date, end_date, as_of_date, True, require_same_pet=True, include_21_days=True)
        windows = sankeys.windows.summarize(base, start_date, end_date, as_of_date, require_same_pet=True, include_21_days=True)
        chosen = sankeys.select_customers(windows)
        rx, rmeta, _ = sankeys.load_source(chosen, period, bmeta['parquet_sha256'], True)
        frozen, _ = sankeys.summarize(chosen, windows['associations'], rx)
        selected, intervals = requests_for(frozen)
        if print_sql:
            click.echo(render_sql(intervals, contact_timezone, all_contacts, all_order_history)); return
        dependencies = dict(baseline=bmeta['parquet_sha256'], prescription_channels=rmeta['parquet_sha256'],
                            customer_selection=sankeys.SELECTION)
        raw, metadata, manifest = load_source(intervals, period, dependencies, contact_timezone, cached, all_contacts, all_order_history)
        outputs = summarize(selected, intervals, raw, contact_timezone, all_contacts, all_order_history)
        if all_contacts:
            outputs = {kind: contact_columns(frame, all_order_history) for kind, frame in outputs.items()}
            outputs['audit']['measure'] = outputs['audit'].measure.str.replace('WISMO', 'contact', regex=False)
        metadata.update(start_date=start_date, end_date_exclusive=end_date, as_of_date=as_of_date)
        tables, prefix = table_layout(ROOT, NAME, period)
        prefix += ('all-handled-contacts_' if all_contacts else '') + ('all-order-history_' if all_order_history else '') + contact_timezone.replace('/', '-') + '_'
        tables.mkdir(parents=True, exist_ok=True)
        note = (f'Frozen REFNUM 24 selected 7/14/21-day same-customer/product/pet reorders; original prescription dates [{start_date}, {end_date}) UTC, '
            f'as-of {as_of_date} 00:00 UTC, each customer counted once per horizon at their shortest qualifying delay. '
            'Join handled WISMO contacts on the ORIGINAL aged ORDER_ID only, with CATEGORY_WISMO_FLAG=TRUE and HANDLED_FLAG=TRUE. '
            f'SESSION_START_DTTM is interpreted as {contact_timezone} and converted to UTC. '
            'The strict interval is original order cancellation < contact session start < selected reorder placement; contacts exactly at either boundary are excluded. '
            'Do not use the reorder ORDER_ID, session end or agent leg start to test the interval. '
            'wismo_contact_count follows COUNT(*) on matching contact legs; distinct sessions are reported separately. '
            'Contacts are order-level evidence, not proof about a specific item or pet. Repeated intervals are extracted once and mapped back to the selected customers/horizons. '
            'Contact/interval counts and horizons can overlap and must not be summed as unique global contacts. '
            'Missing session timestamps cannot meet the time condition and remain in order-level audits. No matching dated contact does not imply no contact ever. '
            'Current source flags and order associations are lookup-time state.\n\n'
            f"Source SHA-256 {metadata['parquet_sha256']}; extracted {metadata['extracted_at_utc']}.\n\n")
        if all_contacts:
            note = note.replace('Join handled WISMO contacts on the ORIGINAL aged ORDER_ID only, with CATEGORY_WISMO_FLAG=TRUE and HANDLED_FLAG=TRUE.',
                'Join all handled contacts on the ORIGINAL aged ORDER_ID only, with HANDLED_FLAG=TRUE and no CATEGORY_WISMO_FLAG filter; true, false and null categories are retained.')
            note = note.replace('wismo_contact_count', 'contact_count')
        if all_order_history:
            note = (f'Frozen REFNUM 24 selected 7/14/21-day same-customer/product/pet reorders; original prescription dates [{start_date}, {end_date}) UTC; '
                f'reorder cohort as-of {as_of_date} 00:00 UTC. Each customer counts once per horizon using their shortest-delay pair. '
                'All available handled contacts on the ORIGINAL aged ORDER_ID, with HANDLED_FLAG=TRUE and no CATEGORY_WISMO_FLAG filter. '
                'There is NO contact time restriction: contacts before cancellation, at either boundary, after reorder, after the cohort cutoff and without timestamps are included. '
                'This is lookup-time order contact history, not contact presence as of the cohort cutoff or before the reorder. '
                f'SESSION_START_DTTM is interpreted as {contact_timezone}; earliest/latest populated times are retained and missing times are counted. '
                'contact_count uses COUNT(*) contact legs; distinct sessions are separate. Evidence is order-level, not item/pet-level. '
                'Repeated original-order lookups map back to customers/horizons; do not sum overlapping horizon/lookup contact totals as unique global contacts. '
                f"Source SHA-256 {metadata['parquet_sha256']}; extracted {metadata['extracted_at_utc']}.\n\n")
        hashes = {}
        for kind, frame in outputs.items():
            table = tables / f'{prefix}{kind}.md'
            heading = 'contacts' if all_contacts else 'WISMO'
            timing = 'all available history' if all_order_history else 'before reorder'
            write_text(table, f'# Aged-order {heading}, {timing}: {kind}\n\n' + note + markdown_table(frame) + '\n')
            path = manifest.parent / f'{kind}.parquet'
            frame.to_parquet(path, index=False)
            hashes[str(path.relative_to(ROOT))] = digest(path)
            hashes[str(table.relative_to(ROOT))] = digest(table)
        write_text(manifest.parent / 'exports.json', json.dumps(dict(dependencies=dependencies, contact_timezone=contact_timezone,
            contact_scope='all-handled' if all_contacts else 'wismo',
            contact_time_scope='all-order-history' if all_order_history else 'strict-cancellation-to-reorder',
            source_sha256=metadata['parquet_sha256'], files=hashes), indent=2) + '\n')
        write_text(manifest, json.dumps(metadata, indent=2) + '\n')
        click.echo(outputs['summary'].to_string(index=False))
        click.echo(outputs['audit'].to_string(index=False))
        click.echo(f'Tables: {tables}')
    except (ValueError, OSError, KeyError, subprocess.CalledProcessError) as error:
        raise click.ClickException(str(error)) from error


if __name__ == '__main__':
    main()
