"""Publish the retained SQL behind the financial report; never query the warehouse."""

import hashlib
import json
from pathlib import Path

from src.python.create_report_sql_listings import format_sql
from src.python.markdown_tables import write_text

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'data/opportunity'
DESTINATION = ROOT / 'src/autogenerated/financial-sql'
PERIOD = '2026-05-01_2026-08-01'
WINDOWS = PERIOD + '_7d-14d-21d-28d-35d-42d-49d-56d-63d-70d_as-of-2026-10-28'
FIRST_WINDOWS = PERIOD + '_7d-70d_as-of-2026-10-28'
BASELINE = 'order-cancellation-summary/' + PERIOD + '/shipped-or-cancelled'
QUERIES = [
    ('baseline', BASELINE, 'summary-report.sql', 'source.json',
     'Baseline extraction and cancellation-reason/line-status aggregation',
     r'Table~\ref{tab:financial-opportunity-cancellations}. This complete report SQL embeds the source extraction '
     'and applies prescription/customer eligibility, shipment deduplication, event-window sales selection and distinct totals.'),
    ('first-upload-history', 'aged-first-customer-upload-vet-diet-order-customers/' + PERIOD, 'query.sql', 'analysis.json',
     'First customer-upload vet-diet order history',
     'Defines the first customer-upload cohort used in the middle column group of each follow-up comparison. '
     'Python selects unambiguous first observed aged-order anchors from this history.'),
    ('first-vet-diet-history', 'aged-first-vet-diet-order-customers/' + PERIOD, 'query.sql', 'analysis.json',
     'First vet-diet order history',
     'Defines the first vet-diet cohort used in the right column group of each follow-up comparison. '
     'Python excludes unknown or ambiguous first-order histories.'),
    ('all-aged-rxp', 'aged-reorder-studies/' + WINDOWS, 'query.sql', 'source.json',
     'RxP follow-up: all aged customers',
     r'Tables~\ref{tab:financial-opportunity-reorder-windows}, '
     r'\ref{tab:financial-opportunity-reorder-same-pet-different-part} and '
     r'\ref{tab:financial-opportunity-reorder-any-vet-diet}, left column groups.'),
    ('first-upload-rxp', 'new-upload-customer-follow-up-studies/' + FIRST_WINDOWS, 'query.sql', 'analysis.json',
     'RxP follow-up: first customer-upload cohort',
     "The same three RxP endpoint tables, middle column groups; only each customer's first qualifying aged order is an anchor."),
    ('first-vet-diet-rxp', 'new-vet-diet-customer-follow-up-studies/' + FIRST_WINDOWS, 'query.sql', 'analysis.json',
     'RxP follow-up: first vet-diet cohort',
     "The same three RxP endpoint tables, right column groups; only each customer's first qualifying aged order is an anchor."),
    ('all-aged-chewy', 'aged-chewy-follow-up/' + WINDOWS, 'query.sql', 'source.json',
     'All-Chewy follow-up: all aged customers',
     r'Table~\ref{tab:financial-opportunity-reorder-all-chewy}, left column group. '
     r'Customer-only matching against \texttt{EDLDB.ECOM.ORDER\_LINE} across all categories.'),
    ('first-upload-chewy', 'new-upload-customer-follow-up-chewy/' + FIRST_WINDOWS, 'query.sql', 'analysis.json',
     'All-Chewy follow-up: first customer-upload cohort',
     r'Table~\ref{tab:financial-opportunity-reorder-all-chewy}, middle column group.'),
    ('first-vet-diet-chewy', 'new-vet-diet-customer-follow-up-chewy/' + FIRST_WINDOWS, 'query.sql', 'analysis.json',
     'All-Chewy follow-up: first vet-diet cohort',
     r'Table~\ref{tab:financial-opportunity-reorder-all-chewy}, right column group.'),
]


def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    lines = [r'\clearpage', r'\subsubsection{SQL used in the financial analysis}',
             r'\label{subsec:financial-analysis-sql}', r'\nolinenumbers',
             r'''These are the retained, parameter-resolved queries behind Tables~\ref{tab:financial-opportunity-cancellations}--\ref{tab:financial-opportunity-reorder-all-chewy}.
The original window is May 1 inclusive to August 1 exclusive, 2026, UTC;
follow-up extends through 70 days, observed through October 28, 2026, 00:00 UTC.
Formatting preserves SQL tokens and the source files remain unchanged.
Preparing these listings does not execute SQL or refresh data.

The baseline listing includes extraction and report aggregation. Follow-up listings
are source extractions, not standalone queries for the displayed percentages.
The three RxP extracts return candidates for all three matching scopes together;
Python applies each endpoint, the ten cumulative 7--70-day windows and whole-order
cancellation/unknown-status exclusions, then counts distinct returning customers
and orders and deduplicates line sales across anchors. Percentages use each
fixed full cohort denominator. RxP sales sum shipment/line contributions;
Chewy sales use the full ECOM line amount once per physical line.
The two history queries supply the frozen first-order cohorts.

The relevant post-extraction implementations are
\path{src/python/create_opportunity_order_cancellation_summary.py},
\path{src/python/create_opportunity_aged_first_order_customers.py},
\path{src/python/create_opportunity_aged_reorders.py} and
\path{src/python/create_opportunity_new_upload_customer_follow_up.py}.
Local DuckDB verification SQL and audit exports remain beside each retained extract.
The separate customer order-frequency analysis remains outside this report.''']
    provenance = {}
    for name, directory, filename, manifest, title, note in QUERIES:
        source = DATA / directory / filename
        sql = source.read_text()
        extraction = (source.parent / 'query.sql').read_text()
        metadata = json.loads((source.parent / manifest).read_text())
        expected = metadata['identity']['sql_sha256']
        # Baseline and whole-cohort writers add one export newline after hashing.
        query_hashes = {hashlib.sha256(value.encode()).hexdigest()
                        for value in (extraction, extraction.removesuffix('\n'))}
        if expected not in query_hashes:
            raise ValueError(f'Retained query does not match its manifest: {source.parent}')
        if filename != 'query.sql' and extraction.strip().rstrip(';') not in sql:
            raise ValueError(f'Baseline aggregation does not embed the retained extraction: {source}')
        write_text(DESTINATION / f'{name}.sql', format_sql(sql, source.name))
        relative = source.relative_to(ROOT).as_posix()
        provenance[name] = dict(source=relative, sha256=hashlib.sha256(sql.encode()).hexdigest(),
                                extraction_sql_sha256=expected)
        lines.extend([r'\clearpage', r'\paragraph*{' + title + '}', note,
                      r'\noindent Source: \path{' + relative + '}.',
                      r'\lstinputlisting[style=verification-sql]{../autogenerated/financial-sql/' + name + '.sql}'])
    lines.append(r'\linenumbers')
    write_text(DESTINATION / 'listings.tex', '\n'.join(lines) + '\n')
    write_text(DESTINATION / 'source-hashes.json', json.dumps(provenance, indent=2) + '\n')
    print(f'Prepared {len(QUERIES)} financial SQL listings from retained, manifest-checked queries.')


if __name__ == '__main__':
    main()
