"""Aged-order status and upload detail using the retained status extraction."""
import json
from pathlib import Path

import pandas as pd

from src.python import create_study_no_cancellation_upload_details as details
from src.python.markdown_tables import markdown_table, write_text

ROOT = details.ROOT
NAME = 'study-aged-order-upload-coverage'
DATA = ROOT / 'data' / NAME / details.coverage.PERIOD


def main():
    cohort, uploads, hashes = details.frozen_inputs('aged order')
    try:
        metadata = json.loads((DATA / 'source.json').read_text())
        if (details.digest(DATA / 'source.parquet') != metadata['parquet_sha256']
                or details.digest(DATA / 'source.sql') != metadata['sql_sha256']):
            raise ValueError('Retained aged-order status snapshot fingerprint differs')
    except (OSError, KeyError) as error:
        raise SystemExit(f'Restore source.parquet, source.sql and source.json under {DATA} '
                         'from the retained aged-order status extraction, then rerun '
                         'make study-aged-order-upload-coverage') from error
    source = pd.read_parquet(DATA / 'source.parquet').rename(columns=str.lower)
    source = source.rename(columns={'status_variants': 'line_status_variants'})
    retained, excluded, summary, audit = details.analyze(source, cohort, uploads, 'aged order')
    if audit['extracted_at_utc'] != metadata['extracted_at_utc']:
        raise ValueError('Status extraction timestamp disagrees with provenance')
    # The retained snapshot covers the complete, unchanged aged-order population.
    if len(excluded):
        raise ValueError('Retained aged-order snapshot has changed cancellation reasons')
    if (summary.prescriptions.sum(), summary.with_upload.sum(), summary.without_upload.sum()) != (26443, 777, 25666):
        raise ValueError('Aged prescription/upload totals differ from the frozen report cohort')
    for name, frame in {'summary': summary, 'retained-lines': retained, 'excluded-lines': excluded}.items():
        frame.to_parquet(DATA / f'{name}.parquet', index=False)
    write_text(DATA / 'verification.sql', '-- Bind parameter: aged order\n' + details.VERIFY_SQL + ';\n')
    write_text(DATA / 'audit.json', json.dumps(audit, indent=2) + '\n')
    write_text(DATA / 'analysis.json', json.dumps(dict(
        source_fingerprints=hashes, status_source=metadata,
        generator_sha256=details.digest(Path(__file__)),
        shared_generator_sha256=details.digest(Path(details.__file__)),
        exports={p.name: details.digest(p) for p in DATA.glob('*.parquet')},
        verification=audit['verification']), indent=2) + '\n')
    total = {**{k: '' for k in details.GROUPS}, 'rx_status': 'TOTAL',
             **summary[details.COUNTS].sum().to_dict()}
    table = pd.concat([summary, pd.DataFrame([total])], ignore_index=True)
    tables = ROOT / 'outputs/tables' / details.coverage.PERIOD
    tables.mkdir(parents=True, exist_ok=True)
    write_text(tables / f'{NAME}.md', '# Aged-order prescription and order status with uploads\n\n' +
               markdown_table(table) + '\n\nAudit: ' + json.dumps(audit) + '\n')
    fragment = r'''% Generated by make study-aged-order-upload-coverage.
\begin{table}[!htbp]
\centering
\caption{Prescription and order statuses for aged-order first-order lines, by retained upload coverage.}
\label{tab:study-aged-order-upload-coverage}
\small
\setlength{\tabcolsep}{6pt}
\begin{tabular}{llllrrrr}
\toprule
RX\_STATUS & Order status & Order cancellation reason & Line-item status & Prescriptions & Line items & With upload & Without upload \\
\midrule
''' + details.latex_rows(summary, highlight=True) + r'''
\bottomrule
\end{tabular}
\begin{minipage}{\linewidth}
\footnotesize
\textit{Notes:} Same columns and counting rules as Table~\ref{tab:study-no-cancellation-upload-details},
for the frozen aged-order subset of Table~\ref{tab:study-upload-coverage-by-cancellation-reason}:
26,443 prescriptions/first-order lines across 24,408 orders. Include cancellations
at or before October 27, 2026, 00:00 UTC; later or undated aged cancellations are excluded.
Statuses are from the retained extraction at ''' + audit['extracted_at_utc'] + r'''.
Prescriptions count distinct \texttt{RX\_ID}s; each physical line counts once.
With/without upload counts lines with/without at least one entity, not entities.
Validate prescription/customer/both first-order keys and shipment-row consistency.
Reuse all entity states and the August 1--October 25 inclusive UTC discovery window,
including the retained unknown-creation-time rule. Uploads need not precede cancellation.
\end{minipage}
\end{table}
'''
    write_text(ROOT / 'src/autogenerated/study_aged_order_upload_coverage.tex', fragment)
    print(table.to_string(index=False))


if __name__ == '__main__':
    main()
