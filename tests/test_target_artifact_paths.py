"""Target routing must work without root compatibility directories."""

from shared.paths import artifact_path, repository_root


def test_export_filename_routes_after_shared_directory_resolution():
    root = repository_root()
    directory = artifact_path(root / "outputs/tables/opportunity/2026-05-01")
    destination = artifact_path(directory / "order-cancellation-summary.md")
    assert destination == root / (
        "targets/cancellation-sales-baseline/outputs/tables/opportunity/"
        "2026-05-01/order-cancellation-summary.md"
    )
    assert artifact_path(destination) == destination


def test_retained_dataset_and_materialized_sql_have_target_owners():
    root = repository_root()
    for category in ("data", "src/autogenerated"):
        path = artifact_path(
            root / category / "aged-order-reorder-wismo/example.sql"
        )
        assert path == (
            root
            / "targets/aged-order-reorder-wismo"
            / category
            / "aged-order-reorder-wismo/example.sql"
        )


def test_retained_latex_and_published_pdf_paths():
    root = repository_root()
    assert artifact_path(root / "src/latex/appendix/contact_analysis.tex") == (
        root
        / "targets/contact-days-relative-to-cancellation/src/latex"
        / "contact_analysis.tex"
    )
    pdf = root / "outputs/reports/pdf/phds-cmpu-aged-orders-analysis.pdf"
    assert artifact_path(pdf) == pdf


def test_prefixed_dataset_name_is_not_stripped_before_matching():
    root = repository_root()
    assert artifact_path(
        root / "data/opportunity-reorder-customer-counts/source.parquet"
    ) == root / (
        "targets/opportunity-reorder-customer-counts/data/"
        "opportunity-reorder-customer-counts/source.parquet"
    )


def test_latex_fragments_resolve_individually_across_owners(tmp_path):
    from shared.paths import latex_fragment_path

    paths = [
        latex_fragment_path(name, root=tmp_path)
        for name in (
            "financial_opportunity.tex",
            "financial_opportunity_follow_up_same_part_pet.tex",
            "financial_opportunity_new_upload_follow_up_same_part_pet.tex",
        )
    ]
    assert len({path.parent for path in paths}) == 3
    assert all(path.is_relative_to(tmp_path / "targets") for path in paths)
    assert not list(tmp_path.iterdir())  # Resolution does not create files.
