"""Execution history stays in ignored cache, outside analytical sources."""

import runpy
from pathlib import Path

import pytest

RUNNER = (
    Path(__file__).parents[1]
    / ".agents/skills/rxp-sql/scripts/run_snowflake_query.py"
)
record_sql = runpy.run_path(str(RUNNER))["record_sql"]


def test_target_history_is_redirected_to_cache(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    requested = Path("targets/example/src/autogenerated/sql-history")
    first = record_sql("SELECT 1", requested, "query.sql")
    second = record_sql("SELECT 1", requested, "query.sql")
    assert first.parent == tmp_path / ".cache/sql-history" / requested
    assert first != second
    assert first.read_text().endswith("SELECT 1\n")
    assert not (tmp_path / "targets").exists()


def test_cache_path_is_not_prefixed_twice(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    record = record_sql("SELECT 1", Path(".cache/sql-history"), "--query")
    assert record.parent == tmp_path / ".cache/sql-history"


@pytest.mark.parametrize("requested", ["../outside", "/tmp/outside"])
def test_history_cannot_escape_workspace(tmp_path, monkeypatch, requested):
    monkeypatch.chdir(tmp_path)
    with pytest.raises(ValueError):
        record_sql("SELECT 1", Path(requested), "--query")
    assert not (tmp_path / ".cache").exists()
