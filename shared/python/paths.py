"""Repository location shared by independently owned analysis generators."""

from functools import lru_cache
from pathlib import Path

import yaml


def repository_root():
    return Path(__file__).resolve().parents[2]


@lru_cache(maxsize=1)
def source_ownership():
    return yaml.safe_load(
        (repository_root() / "shared/source-ownership.yaml").read_text()
    )


def canonical_sql_path(name):
    """Resolve a legacy query name to its single canonical source."""
    return repository_root() / source_ownership()["queries"][name]


@lru_cache(maxsize=1)
def artifact_ownership():
    return yaml.safe_load(
        (repository_root() / "shared/artifact-ownership.yaml").read_text()
    )


def artifact_path(path):
    """Route a historical dataset path to its declared target owner.

    This is explicit compatibility routing, independent of filesystem symlinks.
    It therefore also routes new outputs and empty-cache builds correctly.
    """
    path = Path(path)
    if (
        not path.is_absolute()
        and path.parts
        and path.parts[0] in {"data", "outputs", "src"}
    ):
        path = repository_root() / path
    try:
        relative = path.relative_to(repository_root())
    except ValueError:
        return path
    # Shared export batches choose filenames after constructing a directory.
    # Resolve those final filenames to their owners, even when the directory
    # was already routed to the report's retained staging area.
    for category in ("tables", "figures", "diagrams"):
        staging = Path("targets/report/outputs") / category / "retained"
        if relative.is_relative_to(staging):
            original = "charts" if category == "figures" else category
            relative = (
                Path("outputs") / original / relative.relative_to(staging)
            )
            break
    parts = relative.parts
    if not parts:
        return path
    ownership = artifact_ownership()
    for prefix, destination in sorted(
        ownership.get("path_prefixes", {}).items(),
        key=lambda item: -len(item[0]),
    ):
        if relative.is_relative_to(prefix):
            return (
                repository_root() / destination / relative.relative_to(prefix)
            )
    if parts[0] == "data":
        kind, offset = "data", 1
    elif parts[:2] == ("src", "autogenerated"):
        kind, offset = "src/autogenerated", 2
    elif (
        len(parts) > 2
        and parts[0] == "outputs"
        and parts[1] in {"tables", "charts", "diagrams"}
    ):
        kind, offset = (
            "outputs/" + {"charts": "figures"}.get(parts[1], parts[1]),
            2,
        )
    else:
        return path
    if kind.startswith("outputs/"):
        for prefix, owner in sorted(
            ownership.get("output_prefixes", {}).items(),
            key=lambda item: -len(item[0]),
        ):
            if path.name.startswith(prefix):
                return (
                    repository_root()
                    / "targets"
                    / owner
                    / kind
                    / Path(*parts[offset:])
                )
    for name, owner in sorted(
        ownership["datasets"].items(), key=lambda item: -len(item[0])
    ):
        for index in range(offset, len(parts)):
            component = parts[index]
            if any(
                candidate == name
                or candidate.startswith((name + ".", name + "_"))
                for candidate in (
                    component,
                    component.removeprefix("opportunity-"),
                )
            ):
                suffix = parts[index:] if kind == "data" else parts[offset:]
                return (
                    repository_root()
                    / "targets"
                    / owner
                    / kind
                    / Path(*suffix)
                )
    if kind == "outputs/diagrams":
        raise ValueError(
            f"No target owner for diagram path {path}; use a target-owned "
            "outputs/diagrams path or register its owner in "
            "shared/artifact-ownership.yaml"
        )
    # Preserve otherwise unclassified historical artifacts under the report.
    # New analytical datasets should declare an owner above before use.
    return (
        repository_root()
        / "targets/report"
        / kind
        / "retained"
        / Path(*parts[offset:])
    )


def output_path(path):
    """
    Prepare a canonical generated-file destination before a library writes
    it.
    """
    destination = artifact_path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    return destination


def latex_fragment_path(filename, *, root=None):
    """Resolve a report fragment by filename before reading or writing it.

    Generators can share fragments without sharing a physical directory.
    The optional root supports isolated builds and tests with the same owners.
    """
    filename = str(filename)
    if Path(filename).name != filename:
        raise ValueError(f"Expected a LaTeX fragment filename: {filename}")
    key = "src/latex/appendix/" + filename
    destination = artifact_ownership()["path_prefixes"][key]
    return (repository_root() if root is None else Path(root)) / destination
