"""Repository location shared by independently owned analysis generators."""

from functools import lru_cache
from pathlib import Path

import yaml


def repository_root():
    return Path(__file__).resolve().parents[1]


@lru_cache(maxsize=1)
def source_ownership():
    return yaml.safe_load(
        (repository_root() / "shared/source-ownership.yaml").read_text()
    )


def canonical_sql_path(name):
    """Resolve a legacy query name to its single canonical source."""
    return repository_root() / source_ownership()["queries"][name]


@lru_cache(maxsize=1)
def artifact_ownership():
    return yaml.safe_load(
        (repository_root() / "shared/artifact-ownership.yaml").read_text()
    )


def artifact_path(path):
    """Route a historical dataset path to its declared target owner.

    This is explicit compatibility routing, independent of filesystem symlinks.
    It therefore also routes new outputs and empty-cache builds correctly.
    """
    path = Path(path)
    if (
        not path.is_absolute()
        and path.parts
        and path.parts[0] in {"data", "outputs", "src"}
    ):
        path = repository_root() / path
    try:
        relative = path.relative_to(repository_root())
    except ValueError:
        return path
    parts = relative.parts
    if not parts:
        return path
    if parts[0] == "data":
        kind, offset = "data", 1
    elif parts[:2] == ("src", "autogenerated"):
        kind, offset = "src/autogenerated", 2
    elif (
        len(parts) > 2
        and parts[0] == "outputs"
        and parts[1] in {"tables", "charts", "diagrams"}
    ):
        kind, offset = (
            "outputs/" + {"charts": "figures"}.get(parts[1], parts[1]),
            2,
        )
    else:
        return path
    ownership = artifact_ownership()
    if kind.startswith("outputs/"):
        for prefix, owner in sorted(
            ownership.get("output_prefixes", {}).items(),
            key=lambda item: -len(item[0]),
        ):
            if path.name.startswith(prefix):
                return (
                    repository_root()
                    / "targets"
                    / owner
                    / kind
                    / Path(*parts[offset:])
                )
    for name, owner in sorted(
        ownership["datasets"].items(), key=lambda item: -len(item[0])
    ):
        for index in range(offset, len(parts)):
            component = parts[index].removeprefix("opportunity-")
            if component == name or component.startswith(
                (name + ".", name + "_")
            ):
                suffix = parts[index:] if kind == "data" else parts[offset:]
                return (
                    repository_root()
                    / "targets"
                    / owner
                    / kind
                    / Path(*suffix)
                )
    return path


def output_path(path):
    """
    Prepare a canonical generated-file destination before a library writes
    it.
    """
    destination = artifact_path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    return destination
