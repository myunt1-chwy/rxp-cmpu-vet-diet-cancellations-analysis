"""
Materialize reviewable cohort queries without connecting to the warehouse.
"""

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from shared.python.cohort_queries import render_cohort_query
from shared.python.markdown_tables import write_text
from shared.python.paths import canonical_sql_path, source_ownership


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lint", action="store_true")
    args = parser.parse_args()
    sources, outputs = [], []
    for name in source_ownership()["database_derived_queries"]:
        source = canonical_sql_path(name)
        relative = source.relative_to(ROOT)
        if relative.parts[0] == "targets":
            output = (
                ROOT / Path(*relative.parts[:2]) / "src/autogenerated" / name
            )
        else:
            output = (
                ROOT
                / "targets/report-sql-listings/src/autogenerated"
                / "database-derived-cohorts"
                / name
            )
        write_text(output, render_cohort_query(source))
        sources.append(source)
        outputs.append(output)
        print(output.relative_to(ROOT), flush=True)
    if args.lint:
        return subprocess.run(
            [
                str(ROOT / ".venv/bin/sqlfluff"),
                "lint",
                *map(str, sources + outputs),
            ],
            check=False,
            cwd=ROOT,
        ).returncode
    return 0


if __name__ == "__main__":
    sys.exit(main())
