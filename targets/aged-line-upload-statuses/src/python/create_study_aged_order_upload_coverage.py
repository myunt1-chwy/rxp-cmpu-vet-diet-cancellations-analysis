"""Aged-order status and upload detail using the retained status extraction."""

import json
from pathlib import Path

import pandas as pd

from shared.python import (
    create_study_no_cancellation_upload_details as details,
)
from shared.python.markdown_tables import markdown_table, write_text
from shared.python.paths import artifact_path

ROOT = details.ROOT
NAME = "study-aged-order-upload-coverage"
DATA = artifact_path(ROOT / "data" / NAME / details.coverage.PERIOD)


def main():
    cohort, uploads, hashes = details.frozen_inputs("aged order")
    try:
        metadata = json.loads(
            (artifact_path(DATA / "source.json")).read_text()
        )
        if (
            details.digest(artifact_path(DATA / "source.parquet"))
            != metadata["parquet_sha256"]
            or details.digest(artifact_path(DATA / "source.sql"))
            != metadata["sql_sha256"]
        ):
            raise ValueError(
                "Retained aged-order status snapshot fingerprint differs"
            )
    except (OSError, KeyError) as error:
        raise SystemExit(
            f"Restore source.parquet, source.sql and source.json under {DATA} "
            "from the retained aged-order status extraction, then rerun "
            "make study-aged-order-upload-coverage"
        ) from error
    parent = json.loads((details.PARENT / "analysis.json").read_text())
    if (
        metadata.get("refresh_run_id") != parent.get("refresh_run_id")
        or not metadata.get("refresh_run_id")
        or metadata.get("frozen_inputs") != hashes
        or metadata.get("sql_sha256")
        != details.hashlib.sha256(
            details.render_cohort_query(details.SQL).encode()
        ).hexdigest()
    ):
        raise ValueError("Aged status source mixes runs or dependencies")
    source = pd.read_parquet(artifact_path(DATA / "source.parquet")).rename(
        columns=str.lower
    )
    source = source.rename(columns={"status_variants": "line_status_variants"})
    retained, excluded, summary, audit = details.analyze(
        source,
        cohort,
        uploads,
        "aged order",
        extracted_at_utc=metadata["extracted_at_utc"],
    )
    if audit["extracted_at_utc"] != metadata["extracted_at_utc"]:
        raise ValueError(
            "Status extraction timestamp disagrees with provenance"
        )
    if (
        not retained.rx_id.is_unique
        or retained["order_id"].isna().any()
        or retained["order_line_id"].isna().any()
    ):
        raise ValueError("Retained aged-order keys are missing or duplicated")
    if summary.line_items.sum() != len(retained):
        raise ValueError("Aged-order status groups do not reconcile")
    for name, frame in {
        "summary": summary,
        "retained-lines": retained,
        "excluded-lines": excluded,
    }.items():
        frame.to_parquet(artifact_path(DATA / f"{name}.parquet"), index=False)
    write_text(
        artifact_path(DATA / "verification.sql"),
        "-- Bind parameter: aged order\n" + details.VERIFY_SQL + ";\n",
    )
    write_text(
        artifact_path(DATA / "audit.json"), json.dumps(audit, indent=2) + "\n"
    )
    write_text(
        artifact_path(DATA / "analysis.json"),
        json.dumps(
            {
                "source_fingerprints": hashes,
                "status_source": metadata,
                "generator_sha256": details.digest(Path(__file__)),
                "shared_generator_sha256": details.digest(
                    Path(details.__file__)
                ),
                "exports": {
                    p.name: details.digest(p) for p in DATA.glob("*.parquet")
                },
                "verification": audit["verification"],
            },
            indent=2,
        )
        + "\n",
    )
    total = {
        **{k: "" for k in details.GROUPS},
        "rx_status": "TOTAL",
        **summary[details.COUNTS].sum().to_dict(),
    }
    table = pd.concat([summary, pd.DataFrame([total])], ignore_index=True)
    tables = artifact_path(ROOT / "outputs/tables" / details.coverage.PERIOD)
    tables.mkdir(parents=True, exist_ok=True)
    write_text(
        tables / f"{NAME}.md",
        "# Aged-order prescription and order status with uploads\n\n"
        + markdown_table(table)
        + "\n\nAudit: "
        + json.dumps(audit)
        + "\n",
    )
    fragment = (
        (
            "% Generated by make study-aged-order-upload-"
            "coverage.\n\\begin{table}[!htbp]\n\\centering\n\\captio"
            "n{Prescription and order statuses for aged-order first-"
            "order lines, by retained upload "
            "coverage.}\n\\label{tab:study-aged-order-upload-"
            "coverage}\n\\small\n\\setlength{\\tabcolsep}{6pt}\n\\be"
            "gin{tabular}{llllrrrr}\n\\toprule\nRX\\_STATUS & Order "
            "status & Order cancellation reason & Line-item status "
            "& Prescriptions & Line items & With upload & Without "
            "upload \\\\\n\\midrule\n"
        )
        + details.latex_rows(summary, highlight=True)
        + (
            "\n\\bottomrule\n\\end{tabular}\n\\begin{minipage}{\\lin"
            "ewidth}\n\\footnotesize\n\\textit{Notes:} Same columns "
            "and counting rules as Table~\\ref{tab:study-no-"
            "cancellation-upload-details},\nfor the frozen aged-"
            "order subset of Table~\\ref{tab:study-upload-coverage-"
            "by-cancellation-reason}:\n"
            f"{audit['parent_lines']:,} prescriptions/first-order lines "
            f"across {audit['parent_orders']:,} orders. Include "
            "cancellations\nat or before October 27, 2026, 00:00 "
            "UTC; later or undated aged cancellations are "
            "excluded.\nPrescriptions count distinct \\texttt{RX\\_ID}s; "
            "each physical line counts once.\nWith/without upload "
            "counts lines with/without at least one entity, not "
            "entities.\nValidate prescription/customer/both first-"
            "order keys and shipment-row consistency.\nReuse all "
            "entity states and the August 1--October 25 inclusive "
            "UTC discovery window,\nincluding the retained unknown-"
            "creation-time rule. Uploads need not precede "
            "cancellation.\n\\end{minipage}\n\\end{table}\n"
        )
    )
    write_text(
        artifact_path(
            ROOT / "src/autogenerated/study_aged_order_upload_coverage.tex"
        ),
        fragment,
    )
    print(table.to_string(index=False))


if __name__ == "__main__":
    main()
