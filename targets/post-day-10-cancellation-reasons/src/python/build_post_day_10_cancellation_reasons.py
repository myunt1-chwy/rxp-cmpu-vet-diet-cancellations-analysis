"""
Tabulate cancellation reasons for first-order lines cancelled after day 10.

REFRESH=1 queries Snowflake; the default rebuild reuses the cached Parquet.
"Prescription Issue" is how pharmacists record that no prescription exists
by day 10, so it is grouped with "Aged Order" as an aging-equivalent reason.
"""

import argparse
import hashlib
import json
import subprocess
import sys

import pandas as pd

from shared.python.markdown_tables import markdown_table, write_text
from shared.python.runtime import ROOT, RUNNER, digest
from shared.python.sql_templates import render_sql

TARGET = ROOT / "targets/post-day-10-cancellation-reasons"
PARAMETERS = {
    "start_date": "2026-08-15",
    "end_date": "2026-10-15",
    "cutoff_days": 10,
}
AGING_REASONS = ["Aged Order", "Prescription Issue"]
PARQUET = TARGET / "data/post-day-10-cancellation-reasons.parquet"
METADATA = PARQUET.with_suffix(".json")
COLUMNS = ["Cancellation reason", "Lines", "Share (%)", "Median cancel day"]


def extract(sql):
    query = TARGET / "src/autogenerated/post_day_10_cancellation_reasons.sql"
    write_text(query, sql)
    PARQUET.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            sys.executable,
            str(RUNNER),
            str(query),
            "--output-parquet",
            str(PARQUET.relative_to(ROOT)),
        ],
        cwd=ROOT,
        check=True,
    )
    write_text(
        METADATA,
        json.dumps(
            {
                "parameters": PARAMETERS,
                "sql_sha256": hashlib.sha256(sql.encode()).hexdigest(),
                "parquet_sha256": digest(PARQUET),
            },
            indent=2,
        )
        + "\n",
    )


def load(sql):
    if not PARQUET.is_file() or not METADATA.is_file():
        raise SystemExit(
            "Missing cached extract; run make "
            "post-day-10-cancellation-reasons REFRESH=1"
        )
    metadata = json.loads(METADATA.read_text())
    if metadata["sql_sha256"] != hashlib.sha256(sql.encode()).hexdigest():
        raise SystemExit("Cached extract is stale; rerun with REFRESH=1")
    if metadata["parquet_sha256"] != digest(PARQUET):
        raise SystemExit("Cached Parquet differs from its recorded digest")
    frame = pd.read_parquet(PARQUET).rename(columns=str.lower)
    if frame.order_cancel_reason.duplicated().any() or frame.empty:
        raise SystemExit("Expected one row per cancellation reason")
    return frame


def table(frame):
    total = int(frame.lines.sum())
    frame = frame.sort_values(
        ["lines", "order_cancel_reason"], ascending=[False, True]
    )
    rows = [
        [
            row.order_cancel_reason,
            f"{int(row.lines):,}",
            f"{100 * row.lines / total:.1f}",
            f"{row.median_cancel_day:.1f}",
        ]
        for row in frame.itertuples()
    ]
    aging = int(
        frame.loc[frame.order_cancel_reason.isin(AGING_REASONS), "lines"].sum()
    )
    summary = [
        [
            "Aging-equivalent (Aged Order + Prescription Issue)",
            f"{aging:,}",
            f"{100 * aging / total:.1f}",
            "",
        ],
        ["All cancellations after day 10", f"{total:,}", "100.0", ""],
    ]
    return rows, summary, aging, total


def frame_share(rows, reasons, total):
    lines = sum(
        int(row[1].replace(",", "")) for row in rows if row[0] in reasons
    )
    return 100 * lines / total


def latex_escape(text):
    return text.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def render(rows, summary):
    body = "\n".join(
        " & ".join(map(latex_escape, row)) + r" \\" for row in rows
    )
    totals = "\n".join(
        " & ".join(map(latex_escape, row)) + r" \\" for row in summary
    )
    return (
        "\\begin{longtable}{@{}lrrr@{}}\n"
        "\\caption{Cancellation reasons for first-order lines cancelled more "
        "than 10 days after order placement. Pharmacists record "
        "\\emph{Prescription Issue} when no prescription exists by day 10, "
        "so it is an aging-equivalent reason.}\n"
        "\\label{tab:post-day-10-cancellation-reasons}\\\\\n"
        "\\toprule\n"
        + " & ".join(COLUMNS).replace("%", r"\%")
        + " \\\\\n\\midrule\n\\endfirsthead\n\\toprule\n"
        + " & ".join(COLUMNS).replace("%", r"\%")
        + " \\\\\n\\midrule\n\\endhead\n"
        + body
        + "\n\\midrule\n"
        + totals
        + "\n\\bottomrule\n\\end{longtable}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", choices=["0", "1"], default="0")
    args = parser.parse_args()
    sql = render_sql(
        TARGET / "src/sql/post_day_10_cancellation_reasons.sql.j2",
        **PARAMETERS,
    )
    if args.refresh == "1":
        extract(sql)
    rows, summary, aging, total = table(load(sql))
    org = (
        "#+TITLE: Which cancellation reasons account for first-order "
        "lines cancelled after day 10?\n\n"
    )
    org += (
        "| "
        + " | ".join(COLUMNS)
        + " |\n|"
        + "+".join(["---"] * len(COLUMNS))
        + "|\n"
    )
    org += "".join("| " + " | ".join(row) + " |\n" for row in rows)
    org += "|" + "+".join(["---"] * len(COLUMNS)) + "|\n"
    org += "".join("| " + " | ".join(row) + " |\n" for row in summary)
    tables = TARGET / "outputs/tables"
    write_text(tables / "table.org", org)
    write_text(
        tables / "table.md",
        markdown_table(pd.DataFrame(rows + summary, columns=COLUMNS)) + "\n",
    )
    write_text(
        tables / "provenance.json",
        json.dumps(
            {
                "parameters": PARAMETERS,
                "aging_reasons": AGING_REASONS,
                "aging_lines": aging,
                "total_lines": total,
                "parquet_sha256": digest(PARQUET),
                "org_sha256": digest(tables / "table.org"),
            },
            indent=2,
        )
        + "\n",
    )
    write_text(TARGET / "outputs/latex/visual.tex", render(rows, summary))
    # Parent prose cites these values instead of hand-typed numbers.
    customer = frame_share(
        rows, ["Customer Initiated Cancellation", "Customer Request"], total
    )
    write_text(
        TARGET / "outputs/latex/values.tex",
        "\\newcommand{\\PostDayTenAgingShare}"
        f"{{{100 * aging / total:.1f}\\%}}\n"
        f"\\newcommand{{\\PostDayTenAgingLines}}{{{aging:,}}}\n"
        f"\\newcommand{{\\PostDayTenTotalLines}}{{{total:,}}}\n"
        f"\\newcommand{{\\PostDayTenCustomerShare}}{{{customer:.1f}\\%}}\n",
    )
    print(
        f"Aging-equivalent: {aging:,} of {total:,} "
        f"({100 * aging / total:.1f}%)"
    )


if __name__ == "__main__":
    main()
