def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    lines = [
        r"\clearpage",
        r"\subsubsection{SQL used in the financial analysis}",
        r"\label{subsec:financial-analysis-sql}",
        r"\nolinenumbers",
        (
            "These are the retained, parameter-resolved queries "
            "behind Tables~\\ref{tab:financial-opportunity-"
            "cancellations}--\\ref{tab:financial-opportunity-"
            "reorder-all-chewy}.\nThe original window is May 1 "
            "inclusive to August 1 exclusive, 2026, UTC;\nfollow-up "
            "extends through 70 days, observed through October 28, "
            "2026, 00:00 UTC.\nFormatting preserves SQL tokens and "
            "the source files remain unchanged.\nPreparing these "
            "listings does not execute SQL or refresh data.\n\nThe "
            "baseline listing includes extraction and report "
            "aggregation. Follow-up listings\nare source "
            "extractions, not standalone queries for the displayed "
            "percentages.\nThe three RxP extracts return candidates "
            "for all three matching scopes together;\nPython "
            "applies each endpoint, the ten cumulative 7--70-day "
            "windows and whole-order\ncancellation/unknown-status "
            "exclusions, then counts distinct returning "
            "customers\nand orders and deduplicates line sales "
            "across anchors. Percentages use each\nfixed full "
            "cohort denominator. RxP sales sum shipment/line "
            "contributions;\nChewy sales use the full ECOM line "
            "amount once per physical line.\nThe two history "
            "queries supply the frozen first-order cohorts.\n\nThe "
            "relevant post-extraction implementations "
            "are\n\\path{src/python/create_opportunity_order_"
            "cancellation_summary.py},\n\\path{src/python/create_"
            "opportunity_aged_first_order_"
            "customers.py},\n\\path{src/python/create_opportunity_"
            "aged_reorders.py} and\n\\path{src/python/create_"
            "opportunity_new_upload_customer_follow_up.py}.\nLocal "
            "DuckDB verification SQL and audit exports remain "
            "beside each retained extract.\nThe separate customer "
            "order-frequency analysis remains outside this report."
        ),
    ]
    provenance = {}
    for name, directory, filename, manifest, title, note in QUERIES:
        source = artifact_path(DATA / directory / filename)
        sql = source.read_text()
        extraction = (source.parent / "query.sql").read_text()
        metadata = json.loads((source.parent / manifest).read_text())
        expected = metadata["identity"]["sql_sha256"]
        # Baseline and whole-cohort writers add one export newline after
        # hashing.
        query_hashes = {
            hashlib.sha256(value.encode()).hexdigest()
            for value in (extraction, extraction.removesuffix("\n"))
        }
        if expected not in query_hashes:
            raise ValueError(
                f"Retained query does not match its manifest: {source.parent}"
            )
        if (
            filename != "query.sql"
            and extraction.strip().rstrip(";") not in sql
        ):
            raise ValueError(
                f"Baseline aggregation does not embed the retained "
                f"extraction: {source}"
            )
        write_text(DESTINATION / f"{name}.sql", format_sql(sql, source.name))
        relative = source.relative_to(ROOT).as_posix()
        provenance[name] = {
            "source": relative,
            "sha256": hashlib.sha256(sql.encode()).hexdigest(),
            "extraction_sql_sha256": expected,
        }
        lines.extend(
            [
                r"\clearpage",
                r"\paragraph*{" + title + "}",
                note,
                r"\noindent Source: \path{" + relative + "}.",
                (
                    "\\lstinputlisting[style=verification-sql]{../"
                    "autogenerated/financial-sql/"
                )
                + name
                + ".sql}",
            ]
        )
    lines.append(r"\linenumbers")
    write_text(DESTINATION / "listings.tex", "\n".join(lines) + "\n")
    write_text(
        DESTINATION / "source-hashes.json",
        json.dumps(provenance, indent=2) + "\n",
    )
    print(
        f"Prepared {len(QUERIES)} financial SQL listings from retained, "
        f"manifest-checked queries."
    )


if __name__ == "__main__":
    main()
