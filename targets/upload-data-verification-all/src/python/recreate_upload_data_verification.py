"""
Recreate the six upload-source appendix tables using the existing analyses.
"""

import subprocess
import sys

import click

from shared.python.paths import (
    artifact_path,
    canonical_sql_path,
    repository_root,
)

ROOT = repository_root()
RUNNER = artifact_path(
    ROOT / ".agents/skills/rxp-sql/scripts/run_snowflake_query.py"
)
# Each query writes the exact input filename expected by its existing renderer.
ANALYSES = [
    (
        "upload-data-verification",
        "create_upload_data_verification",
        [
            ("upload_data_verification_rx_ids_validation", "rx-id-validation"),
        ],
    ),
    (
        "upload-source-time-coverage",
        "analyze_upload_source_time_coverage",
        [
            ("upload_source_time_coverage", "source"),
        ],
    ),
    (
        "upload-vet-diet-approval-channels",
        "analyze_upload_vet_diet_approval_channels",
        [
            ("upload_vet_diet_approval_channels", "source"),
            ("upload_vet_diet_approval_channels_validation", "validation"),
        ],
    ),
    (
        "cmpu-approved-prescription-upload-coverage",
        "analyze_cmpu_approved_prescription_upload_coverage",
        [
            ("cmpu_approved_prescription_upload_coverage", "source"),
            (
                "cmpu_approved_prescription_upload_coverage_validation",
                "validation",
            ),
        ],
    ),
    (
        "diet-upload-source-cancellation-reasons",
        "analyze_diet_upload_source_orders",
        [
            ("diet_upload_source_orders", "uploads"),
            ("diet_upload_linked_orders", "orders"),
            ("diet_upload_source_orders_validation", "validation"),
        ],
    ),
    (
        "null-resource-upload-analysis",
        "analyze_null_resource_uploads",
        [
            ("null_resource_upload_context", "uploads"),
            ("null_resource_upload_orders", "orders"),
            ("null_resource_upload_validation", "validation"),
        ],
    ),
]


def run(arguments):
    subprocess.run(
        [sys.executable, *map(str, arguments)], cwd=ROOT, check=True
    )


@click.command()
@click.option(
    "--cached",
    is_flag=True,
    help="Render retained extracts without Snowflake access.",
)
def main(cached):
    if cached:
        required = [
            artifact_path(ROOT / "data/upload-data-verification" / name)
            for name in ["source.parquet", "source.json"]
        ]
        required.extend(
            artifact_path(ROOT / "data" / directory / f"{output}.parquet")
            for directory, _, queries in ANALYSES
            for _, output in queries
        )
        missing = [
            str(path.relative_to(ROOT))
            for path in required
            if not path.is_file()
        ]
        if missing:
            raise click.ClickException(
                "Missing retained inputs; rerun without CACHED=1:\n"
                + "\n".join(missing)
            )

    for directory, module, queries in ANALYSES:
        click.echo(f"Recreating {directory}")
        # The original entry-count module already owns its extraction and
        # cache.
        if module == "create_upload_data_verification":
            run(
                [
                    "-m",
                    f"shared.python.{module}",
                    *(["--cached"] if cached else []),
                ]
            )
        if not cached:
            for query, output in queries:
                run(
                    [
                        RUNNER,
                        canonical_sql_path(f"{query}.sql"),
                        "--output-parquet",
                        artifact_path(
                            ROOT / "data" / directory / f"{output}.parquet"
                        ).relative_to(ROOT),
                        "--sql-log-dir",
                        artifact_path(
                            ROOT
                            / "src/autogenerated"
                            / directory
                            / "sql-history"
                        ).relative_to(ROOT),
                    ]
                )
        if module != "create_upload_data_verification":
            run(["-m", f"shared.python.{module}"])


if __name__ == "__main__":
    main()
